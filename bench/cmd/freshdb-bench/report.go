package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// cmdReport merges every *.json result in a directory into one markdown file.
// It prints every run it finds: nothing is filtered or picked.
func cmdReport(args []string) {
	fs := flag.NewFlagSet("report", flag.ExitOnError)
	dir := fs.String("dir", "results", "directory with result JSON files")
	out := fs.String("o", "", "output markdown (default <dir>/results.md)")
	fs.Parse(args)
	if *out == "" {
		*out = filepath.Join(*dir, "results.md")
	}
	files, _ := filepath.Glob(filepath.Join(*dir, "*.json"))
	sort.Strings(files)
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }
	w("# freshdb-bench results\n\nGenerated by `freshdb-bench report` from %d result files in this directory. Every run in every file is listed. Latencies are milliseconds; `open` = open-loop at a fixed rate with latency measured from the intended start time (coordinated-omission corrected); `closed` = closed loop (max throughput, latency per op).\n\n", len(files))
	envDone := false
	for _, f := range files {
		raw, err := os.ReadFile(f)
		if err != nil {
			fatal(err)
		}
		var r map[string]any
		if err := json.Unmarshal(raw, &r); err != nil {
			fatal(fmt.Errorf("%s: %w", f, err))
		}
		env, _ := r["env"].(map[string]any)
		if !envDone && env != nil {
			w("## Environment (from %s)\n\n", filepath.Base(f))
			for _, k := range []string{"cpu", "cpus", "mem_total", "disk", "os", "kernel", "go_version", "freshdb_commit"} {
				w("- %s: %v\n", k, env[k])
			}
			w("\n")
			envDone = true
		}
		w("## %s\n\n", filepath.Base(f))
		if env != nil {
			w("Command: `%v`  \nStarted %v, loadavg at start %v\n\n", env["command"], env["time"], env["loadavg_at_start"])
		}
		if p, ok := r["params"].(map[string]any); ok {
			keys := make([]string, 0, len(p))
			for k := range p {
				keys = append(keys, k)
			}
			sort.Strings(keys)
			w("Params:")
			for _, k := range keys {
				w(" %s=%v;", k, js(p[k]))
			}
			w("\n\n")
		}
		runs, _ := r["runs"].([]any)
		switch r["suite"] {
		case "ycsb":
			w("| sys | fsync | wl | clients | closed ops/s | closed p50 | p99 | p99.9 | open target/s | open achieved/s | open p50 | p99 | p99.9 | errors (closed/open) | open not issued (overload) | open-phase Go GC (cycles, max STW ms) |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|\n")
			for _, x := range runs {
				m := x.(map[string]any)
				c, _ := m["closed_loop"].(map[string]any)
				o, _ := m["open_loop"].(map[string]any)
				gc := "-"
				if g, ok := o["go_gc"].(map[string]any); ok {
					gc = fmt.Sprintf("%v, %v", g["cycles"], g["stw_pause_max_ms"])
				}
				w("| %v | %v | %v | %v | %s | %s | %s | %s | %s | %s | %s | %s | %s | %v/%v | %v | %s |\n", m["system"], m["fsync"], m["workload"], m["clients"],
					num(c, "ops_per_sec"), ms(c, "p50_us"), ms(c, "p99_us"), ms(c, "p999_us"),
					num(o, "target_ops_per_sec"), num(o, "ops_per_sec"), ms(o, "p50_us"), ms(o, "p99_us"), ms(o, "p999_us"), get(c, "errors"), get(o, "errors"), get(o, "not_issued_overload"), gc)
			}
		case "msg":
			w("| sys | fsync | kind | target/s | producers | groups | publish/s | consume/s/group | backlog | publish p50 | p99 | e2e p50 | e2e p99 | e2e p99.9 | errors |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|\n")
			for _, x := range runs {
				m := x.(map[string]any)
				w("| %v | %v | %v | %v | %v | %v | %v | %v | %v | %s | %s | %s | %s | %s | %v |\n", m["system"], m["fsync"], m["kind"], get(m, "target_rate"), m["producers"], m["groups"],
					m["publish_per_sec"], get(m, "consume_per_sec_per_group"), get(m, "backlog_at_end"), lms(m, "publish_latency", "p50_us"), lms(m, "publish_latency", "p99_us"),
					lms(m, "end_to_end_latency", "p50_us"), lms(m, "end_to_end_latency", "p99_us"), lms(m, "end_to_end_latency", "p999_us"), get(m, "errors"))
			}
		case "s3":
			w("| kind | clients | keys/txn | commits/s | keys/s | p50 | p99 | p99.9 | PUT/commit | GET+LIST/commit | est. $/1M commits | est. $/1M keys | segments | open median ms | open requests |\n|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|\n")
			for _, x := range runs {
				m := x.(map[string]any)
				w("| %v | %v | %v | %v | %v | %s | %s | %s | %v | %v | %v | %v | %v | %v | %v |\n", m["kind"], get(m, "clients"), get(m, "keys_per_txn"), get(m, "commits_per_sec"), get(m, "keys_per_sec"),
					lms(m, "commit_latency", "p50_us"), lms(m, "commit_latency", "p99_us"), lms(m, "commit_latency", "p999_us"),
					get(m, "put_requests_per_commit"), get(m, "get_list_requests_per_commit"), get(m, "est_usd_per_million_commits"), get(m, "est_usd_per_million_keys"),
					get(m, "segments"), get(m, "open_ms_median"), js(m["open_requests"]))
			}
		case "vector":
			w("| sys | n | dim | clients | recall@10 | QPS | p50 | p99 | index |\n|---|---|---|---|---|---|---|---|---|\n")
			for _, x := range runs {
				m := x.(map[string]any)
				w("| %v | %v | %v | %v | %v | %v | %s | %s | %v |\n", m["system"], m["n"], m["dim"], m["clients"], m["recall_at_10"], m["qps"], lms(m, "latency", "p50_us"), lms(m, "latency", "p99_us"), get(m, "index"))
			}
		case "calib":
			w("| what | clients | rate | p50 | p99 | p99.9 | max |\n|---|---|---|---|---|---|---|\n")
			for _, x := range runs {
				m := x.(map[string]any)
				w("| %v | %v | %v | %s | %s | %s | %s |\n", m["what"], get(m, "clients"), get(m, "rate"), lms(m, "latency", "p50_us"), lms(m, "latency", "p99_us"), lms(m, "latency", "p999_us"), lms(m, "latency", "max_us"))
			}
		case "txn":
			w("OCC transfers between hot keys:\n\n| sys | fsync | clients | hot keys | commits/s | abort rate | gave up | p50 | p99 | p99.9 | invariant |\n|---|---|---|---|---|---|---|---|---|---|---|\n")
			for _, x := range runs {
				m := x.(map[string]any)
				if _, ok := m["hot_keys"]; !ok {
					continue
				}
				w("| %v | %v | %v | %v | %v | %v | %v | %s | %s | %s | %v |\n", m["system"], m["fsync"], m["clients"], m["hot_keys"], m["commits_per_sec"], m["abort_rate"], get(m, "gave_up_after_16_retries"),
					lms(m, "latency_incl_retries", "p50_us"), lms(m, "latency_incl_retries", "p99_us"), lms(m, "latency_incl_retries", "p999_us"), m["invariant_ok"])
			}
			w("\nMulti-lens consume+write transaction (freshDB only):\n\n| fsync | partitions | batch | txns/s | msgs/s | p50 | p99 | p99.9 | exactly-once check | input drained early | errors |\n|---|---|---|---|---|---|---|---|---|---|---|\n")
			for _, x := range runs {
				m := x.(map[string]any)
				if _, ok := m["partitions"]; !ok {
					continue
				}
				w("| %v | %v | %v | %v | %v | %s | %s | %s | %v | %v | %v |\n", m["fsync"], m["partitions"], m["batch"], m["txns_per_sec"], m["msgs_per_sec"],
					lms(m, "txn_latency", "p50_us"), lms(m, "txn_latency", "p99_us"), lms(m, "txn_latency", "p999_us"), m["exactly_once_check"], get(m, "input_drained"), get(m, "errors"))
			}
		default:
			for _, x := range runs {
				w("- `%s`\n", js(x))
			}
		}
		if notes, ok := r["notes"].([]any); ok && len(notes) > 0 {
			w("\nNotes:\n")
			for _, n := range notes {
				w("- %v\n", n)
			}
		}
		w("\n")
	}
	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		fatal(err)
	}
	fmt.Println("wrote", *out)
}

func js(v any) string {
	switch v.(type) {
	case string, float64, bool, nil:
		return fmt.Sprint(v)
	}
	b, _ := json.Marshal(v)
	return string(b)
}

func get(m map[string]any, k string) any {
	if m == nil {
		return "-"
	}
	if v, ok := m[k]; ok {
		return js(v)
	}
	return "-"
}

func num(m map[string]any, k string) string {
	if m == nil {
		return "-"
	}
	if v, ok := m[k].(float64); ok {
		return fmt.Sprintf("%.0f", v)
	}
	return "-"
}

func ms(m map[string]any, k string) string {
	if m == nil {
		return "-"
	}
	l, _ := m["latency"].(map[string]any)
	return lmsv(l, k)
}

func lms(m map[string]any, lat, k string) string {
	l, _ := m[lat].(map[string]any)
	return lmsv(l, k)
}

func lmsv(l map[string]any, k string) string {
	if l == nil {
		return "-"
	}
	v, ok := l[k].(float64)
	if !ok {
		return "-"
	}
	switch {
	case v < 100:
		return fmt.Sprintf("%.3f", v/1000)
	case v < 10000:
		return fmt.Sprintf("%.2f", v/1000)
	default:
		return fmt.Sprintf("%.1f", v/1000)
	}
}
